    #[test]
    fn brew_cellar_path_maps_to_the_opt_link() {
        let p = Path::new("/opt/homebrew/Cellar/grove/0.2.0/bin/grove");
        assert_eq!(
            brew_opt_path(p).as_deref(),
            Some(Path::new("/opt/homebrew/opt/grove/bin/grove"))
        );
        let linux = Path::new("/home/linuxbrew/.linuxbrew/Cellar/grove/1.0.0_1/bin/grove");
        assert_eq!(
            brew_opt_path(linux).as_deref(),
            Some(Path::new("/home/linuxbrew/.linuxbrew/opt/grove/bin/grove"))
        );
    }

    #[test]
    fn other_paths_have_no_opt_link() {
        for p in [
            "/Users/me/.cargo/bin/grove",
            "/Users/me/.local/bin/grove",
            "/opt/homebrew/Cellar/tmux/3.5/bin/tmux",
            "/opt/homebrew/Cellar/grove",
        ] {
            assert_eq!(brew_opt_path(Path::new(p)), None, "{p}");
        }
    }

    #[test]
    fn hooks_json_registers_every_event_in_exec_form() {
        let bin = Path::new("/Apps/My Tools/grove");
        let v = hooks_json(bin, true);
        let hooks = v["hooks"].as_object().unwrap();
        assert_eq!(hooks.len(), HOOK_EVENTS.len());
        for ev in HOOK_EVENTS {
            let h = &hooks[ev][0]["hooks"][0];
            assert_eq!(h["type"], "command", "{ev}");
            assert_eq!(h["command"], "/Apps/My Tools/grove", "{ev}");
            assert_eq!(h["args"], serde_json::json!(["hook"]), "{ev}");
        }
    }

    #[test]
    fn hooks_json_sets_the_status_line() {
        let v = hooks_json(Path::new("/Apps/My Tools/grove"), true);
        let s = &v["statusLine"];
        assert_eq!(s["type"], "command");
        // A shell string, unlike hooks' exec form: the space must be quoted.
        assert_eq!(s["command"], "'/Apps/My Tools/grove' statusline");
        assert_eq!(s["padding"], 2);
        let odd = hooks_json(Path::new("/it's/grove"), true);
        assert_eq!(odd["statusLine"]["command"], r"'/it'\''s/grove' statusline");
    }

    #[test]
