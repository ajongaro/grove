//! Files Grove regenerates on every start under `run/`: the hooks settings
//! file, the MCP config, and Grove's tmux config.

use std::path::Path;

use anyhow::Result;
use serde_json::json;

use crate::config::Paths;
use crate::store::write_atomic;

/// Every hook event Grove listens to (see state.rs).
pub const HOOK_EVENTS: [&str; 9] = [
    "SessionStart",
    "UserPromptSubmit",
    "PostToolUse",
    "PostToolUseFailure",
    "PermissionRequest",
    "Notification",
    "Stop",
    "StopFailure",
    "SessionEnd",
];

/// Settings file passed to every session with `--settings`. Exec form
/// (`command` + `args`) so a binary path with spaces needs no quoting.
pub fn hooks_json(grove_bin: &Path) -> serde_json::Value {
    let handler = json!([{ "hooks": [{
        "type": "command",
        "command": grove_bin.to_string_lossy(),
        "args": ["hook"],
        "timeout": 10,
    }]}]);
    let hooks: serde_json::Map<String, serde_json::Value> = HOOK_EVENTS
        .iter()
        .map(|e| (e.to_string(), handler.clone()))
        .collect();
    json!({ "hooks": hooks })
}

pub fn mcp_json(grove_bin: &Path) -> serde_json::Value {
    json!({ "mcpServers": { "grove": { "command": grove_bin.to_string_lossy(), "args": ["mcp"] } } })
}

/// Grove's tmux config: stock tmux plus only what Grove needs (its keys, Esc
/// without delay, true colour, clipboard). Loaded only by Grove's tmux server
/// (`tmux -L grove -f run/tmux.conf`), so `~/.tmux.conf` doesn't apply;
/// `~/.grove/tmux.local.conf` is sourced last for your own setup.
/// `clip` is the clipboard command copies are piped to (None: tmux buffer +
/// OSC 52).
pub fn tmux_conf(session: &str, paths: &Paths, clip: Option<&str>) -> String {
    let self_path = paths.run.join("tmux.conf");
    let local_path = paths.home.join("tmux.local.conf");
    // The default copy bindings (both key tables, and mouse drag) pipe to
    // copy-command, so setting it is enough; no keys are rebound.
    let copy = clip
        .map(|c| format!("set -s copy-command \"{c}\"\n"))
        .unwrap_or_default();
    let base = r##"# Generated by grove on every start. Put your own tmux setup in
# ~/.grove/tmux.local.conf (loaded last), not this file.

# Esc reaches the dashboard at once instead of waiting for a key sequence.
set -s escape-time 0
# Project and finca colours are hex.
set -sa terminal-overrides ",xterm*:Tc"
# Window names carry Grove's needs-you marker; programs mustn't overwrite them.
set -g allow-rename off
set -g mouse on
# Copies also reach the outer terminal's clipboard (OSC 52), e.g. from a finca.
set -s set-clipboard on
set -g status-left "#[bold] GROVE "
set -g status-left-length 12

# Dashboard by name, so window numbering (base-index) doesn't matter.
bind -n C-y select-window -t :=dashboard
"##;
    // Finca sessions use the grove-finca table instead of root (finca.rs), so
    // only C-q is intercepted and every other key reaches the remote grove.
    format!(
        "{base}bind -T grove-finca C-q switch-client -t ={session}\n\
         bind r source-file \"{}\" \\; display \"Reloaded Grove tmux config\"\n\
         {copy}\
         \n# Your own setup, loaded last.\n\
         source-file -q \"{}\"\n",
        self_path.display(),
        local_path.display(),
    )
}

pub fn clipboard_cmd(os: &str, over_ssh: bool, has: &dyn Fn(&str) -> bool) -> Option<String> {
    if over_ssh {
        return None;
    }
    match os {
        "macos" => Some("pbcopy".into()),
        _ if has("wl-copy") => Some("wl-copy".into()),
        _ if has("xsel") => Some("xsel --clipboard --input".into()),
        _ if has("xclip") => Some("xclip -selection clipboard".into()),
        _ => None,
    }
}

/// Whether `prog` is on PATH.
fn on_path(prog: &str) -> bool {
    std::env::var_os("PATH")
        .is_some_and(|p| std::env::split_paths(&p).any(|d| d.join(prog).is_file()))
}

pub fn write_all(paths: &Paths, grove_bin: &Path, session: &str) -> Result<()> {
    let pretty = |v: serde_json::Value| serde_json::to_string_pretty(&v).map(String::into_bytes);
    write_atomic(
        &paths.run.join("hooks.json"),
        &pretty(hooks_json(grove_bin))?,
    )?;
    write_atomic(&paths.run.join("mcp.json"), &pretty(mcp_json(grove_bin))?)?;
    write_atomic(
        &paths.run.join("tmux.conf"),
        tmux_conf(
            session,
            paths,
            clipboard_cmd(
                std::env::consts::OS,
                std::env::var_os("SSH_CONNECTION").is_some(),
                &on_path,
            )
            .as_deref(),
        )
        .as_bytes(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hooks_json_registers_every_event_in_exec_form() {
        let bin = Path::new("/Apps/My Tools/grove");
        let v = hooks_json(bin);
        let hooks = v["hooks"].as_object().unwrap();
        assert_eq!(hooks.len(), HOOK_EVENTS.len());
        for ev in HOOK_EVENTS {
            let h = &hooks[ev][0]["hooks"][0];
            assert_eq!(h["type"], "command", "{ev}");
            assert_eq!(h["command"], "/Apps/My Tools/grove", "{ev}");
            assert_eq!(h["args"], serde_json::json!(["hook"]), "{ev}");
        }
    }

    #[test]
    fn mcp_json_points_at_grove_mcp() {
        let v = mcp_json(Path::new("/b/grove"));
        assert_eq!(v["mcpServers"]["grove"]["command"], "/b/grove");
        assert_eq!(v["mcpServers"]["grove"]["args"], serde_json::json!(["mcp"]));
    }

    fn paths() -> (tempfile::TempDir, Paths) {
        let d = tempfile::tempdir().unwrap();
        let p = Paths::new(d.path().join("grove home"));
        (d, p)
    }

    #[test]
    fn tmux_conf_leaves_stock_tmux_keys_alone() {
        let (_d, p) = paths();
        let c = tmux_conf("grove", &p, Some("pbcopy"));
        for personal in [
            "prefix",
            "split-window",
            "mode-keys",
            "set -g base-index",
            "select-pane",
            "is_vim",
            "copy-mode",
        ] {
            assert!(
                !c.contains(personal),
                "{personal} belongs in tmux.local.conf\n{c}"
            );
        }
        assert!(c.contains("set -s escape-time 0"), "{c}");
    }

    #[test]
    fn tmux_conf_has_grove_keys_and_loads_local_tweaks_last() {
        let (_d, p) = paths();
        let c = tmux_conf("g2", &p, None);
        assert!(
            c.contains("bind -n C-y select-window -t :=dashboard"),
            "{c}"
        );
        assert!(
            c.contains("bind -T grove-finca C-q switch-client -t =g2"),
            "{c}"
        );
        let local = format!(
            "source-file -q \"{}\"",
            p.home.join("tmux.local.conf").display()
        );
        let at = c.find(&local).expect("local tweaks sourced");
        assert!(
            c[at..].lines().count() <= 2,
            "local tweaks must come last:\n{}",
            &c[at..]
        );
        assert!(c.contains(&format!(
            "bind r source-file \"{}\"",
            p.run.join("tmux.conf").display()
        )));
    }

    #[test]
    fn copy_without_a_clipboard_tool_uses_tmux_buffer_and_osc52() {
        let (_d, p) = paths();
        let c = tmux_conf("grove", &p, None);
        assert!(!c.contains("copy-command"), "{c}");
        assert!(c.contains("set -s set-clipboard on"), "{c}");
    }

    #[test]
    fn copies_pipe_to_the_clipboard_tool() {
        let (_d, p) = paths();
        let c = tmux_conf("grove", &p, Some("pbcopy"));
        assert!(c.contains("set -s copy-command \"pbcopy\""), "{c}");
    }

    #[test]
    fn clipboard_tool_choice() {
        let none = |_: &str| false;
        let only = |want: &'static str| move |t: &str| t == want;
        assert_eq!(
            clipboard_cmd("macos", false, &none).as_deref(),
            Some("pbcopy")
        );
        // Over ssh the machine's own clipboard is the wrong one: rely on OSC 52.
        assert_eq!(clipboard_cmd("macos", true, &none), None);
        assert_eq!(
            clipboard_cmd("linux", false, &only("wl-copy")).as_deref(),
            Some("wl-copy")
        );
        assert_eq!(
            clipboard_cmd("linux", false, &only("xsel")).as_deref(),
            Some("xsel --clipboard --input")
        );
        assert_eq!(
            clipboard_cmd("linux", false, &only("xclip")).as_deref(),
            Some("xclip -selection clipboard")
        );
        assert_eq!(clipboard_cmd("linux", false, &none), None);
        assert_eq!(clipboard_cmd("linux", true, &only("xsel")), None);
    }

    #[test]
    fn real_tmux_accepts_the_generated_config() {
        let (_d, p) = paths();
        std::fs::create_dir_all(&p.home).unwrap();
        std::fs::write(
            p.home.join("tmux.local.conf"),
            "set -g @grove_local_loaded yes\nset -g base-index 1\n",
        )
        .unwrap();
        let conf = p.home.join("tmux.conf");
        std::fs::write(&conf, tmux_conf("grove", &p, Some("pbcopy"))).unwrap();
        let tmux = crate::tmux::Tmux {
            config: Some(conf),
            ..crate::tmux::Tmux::new(format!("grove-test-{}-conf", std::process::id()))
        };
        let out = tmux
            .cmd()
            .args(["new-session", "-d", "-s", "grove", "sleep", "30"])
            .output()
            .unwrap();
        let errs = String::from_utf8_lossy(&out.stderr).to_string();
        let show = |args: &[&str]| {
            String::from_utf8(tmux.cmd().args(args).output().unwrap().stdout).unwrap()
        };
        let prefix = show(&["show-options", "-gv", "prefix"]);
        let copy_cmd = show(&["show-options", "-sv", "copy-command"]);
        let base = show(&["show-options", "-gv", "base-index"]);
        let local = show(&["show-options", "-gv", "@grove_local_loaded"]);
        let keys = show(&["list-keys"]);
        tmux.kill_server();
        assert!(
            out.status.success() && errs.is_empty(),
            "tmux rejected the config: {errs}"
        );
        assert_eq!(prefix.trim(), "C-b", "stock prefix");
        assert_eq!(copy_cmd.trim(), "pbcopy");
        // Local settings override Grove's (the dashboard is found by name).
        assert_eq!(base.trim(), "1");
        assert_eq!(local.trim(), "yes");
        assert!(
            keys.lines().any(|l| l.contains("-T root")
                && l.split_whitespace().any(|w| w == "C-y")
                && l.ends_with("select-window -t :=dashboard")),
            "{keys}"
        );
    }

    #[test]
    fn write_all_writes_valid_files_under_spaced_home() {
        let dir = tempfile::tempdir().unwrap();
        let paths = Paths::new(dir.path().join("my grove"));
        write_all(&paths, Path::new("/b/grove"), "grove").unwrap();
        for f in ["hooks.json", "mcp.json"] {
            let text = std::fs::read_to_string(paths.run.join(f)).unwrap();
            serde_json::from_str::<serde_json::Value>(&text).unwrap();
        }
        assert!(paths.run.join("tmux.conf").is_file());
    }
}
