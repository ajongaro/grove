/// Every hook event Grove listens to (see state.rs).
pub const HOOK_EVENTS: [&str; 9] = [
    "SessionStart",
    "UserPromptSubmit",
    "PostToolUse",
    "PostToolUseFailure",
    "PermissionRequest",
    "Notification",
    "Stop",
    "StopFailure",
    "SessionEnd",
];

/// Settings file passed to every session with `--settings`. Exec form
/// (`command` + `args`) so a binary path with spaces needs no quoting.
/// Every hook goes to `grove hook`; with `statusline`, Grove's status line
/// too. Command-line settings outrank the user's, so it only applies inside
/// Grove.
pub fn hooks_json(grove_bin: &Path, statusline: bool) -> serde_json::Value {
    let handler = json!([{ "hooks": [{
        "type": "command",
        "command": grove_bin.to_string_lossy(),
        "args": ["hook"],
        "timeout": 10,
    }]}]);
    let hooks: serde_json::Map<String, serde_json::Value> = HOOK_EVENTS
        .iter()
        .map(|e| (e.to_string(), handler.clone()))
        .collect();
    let mut v = json!({ "hooks": hooks });
    if statusline {
        // A shell command line, unlike the hooks' exec form.
        let bin = grove_bin.to_string_lossy().replace('\'', r"'\''");
        v["statusLine"] = json!({
            "type": "command",
            "command": format!("'{bin}' statusline"),
            "padding": 2,
        });
    }
    v
}

pub fn mcp_json(grove_bin: &Path) -> serde_json::Value {
    json!({ "mcpServers": { "grove": { "command": grove_bin.to_string_lossy(), "args": ["mcp"] } } })
}

/// Grove's tmux config: stock tmux plus only what Grove needs (its keys, Esc
/// without delay, true colour, clipboard). Loaded only by Grove's tmux server
/// (`tmux -L grove -f run/tmux.conf`), so `~/.tmux.conf` doesn't apply;
/// `~/.grove/tmux.local.conf` is sourced last for your own setup.
/// `clip` is the clipboard command copies are piped to (None: tmux buffer +
/// OSC 52).
pub fn tmux_conf(session: &str, paths: &Paths, clip: Option<&str>, theme: &Theme) -> String {
    let self_path = paths.run.join("tmux.conf");
    let local_path = paths.home.join("tmux.local.conf");
    // The default copy bindings (both key tables, and mouse drag) pipe to
    // copy-command, so setting it is enough; no keys are rebound.
    let copy = clip
        .map(|c| format!("set -s copy-command \"{c}\"\n"))
        .unwrap_or_default();
    let base = r##"# Generated by grove on every start. Put your own tmux setup in
# ~/.grove/tmux.local.conf (loaded last), not this file.

# Esc reaches the dashboard at once instead of waiting for a key sequence.
set -s escape-time 0
# Project and finca colours are hex.
set -sa terminal-overrides ",xterm*:Tc"
# Window names carry Grove's needs-you marker; programs mustn't overwrite them.
set -g allow-rename off
set -g mouse on
# Lets tmux know when its terminal has focus, so alerts skip what you're watching.
set -g focus-events on
# Copies also reach the outer terminal's clipboard (OSC 52), e.g. from a finca.
set -s set-clipboard on
# Vim-style copy mode (prefix [): v selects, y copies, also to the clipboard
# command when one is set; C-h/j/k/l still move between panes.
setw -g mode-keys vi
bind -T copy-mode-vi v send-keys -X begin-selection
bind -T copy-mode-vi y send-keys -X copy-pipe-and-cancel
bind -T copy-mode-vi C-h select-pane -L
bind -T copy-mode-vi C-j select-pane -D
bind -T copy-mode-vi C-k select-pane -U
bind -T copy-mode-vi C-l select-pane -R
# Splits open in the pane's folder rather than the session's.
bind '"' split-window -v -c "#{pane_current_path}"
bind % split-window -h -c "#{pane_current_path}"
set -g status-left-length 12
# The dashboard lists every session, so the bar shows only the window you're
# in and those that need you (💧, ui/run.rs). Hidden windows render empty, so
# the spacing lives in the formats rather than the separator. Their colours
# follow the theme (tmux_theme, below).
setw -g window-status-separator ""

# Dashboard by name, so window numbering (base-index) doesn't matter.
# (Its session by name too, so C-g works from the pinned desk.)
# Older Groves took C-y (Claude's yank); re-sourcing never unbinds it.
unbind -n C-y
"##;
    // Finca sessions use the grove-finca table instead of root (finca.rs), so
    // only C-q is intercepted and every other key reaches the remote grove.
    // Finca shells use grove-shell: C-q too, but the prefix still works.
    let exe = grove_exe()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_else(|_| "grove".into());
    let paste = format!(
        "run-shell -b \"'{}' paste --session '#{{session_name}}' --pane '#{{pane_id}}' >/dev/null 2>&1\"",
        exe.replace(['\'', '"'], "")
    );
    // A shell below the session (side.rs). On the desk the key goes on to
    // the column, whose own session opens it under the session shown.
    let side = format!(
        "bind -n 'C-\\' if -F \"#{{==:#{{session_name}},{desk}}}\" \"send-keys 'C-\\\\'\" \"run-shell -b \\\"'{exe}' side-shell --pane '#{{pane_id}}' >/dev/null 2>&1\\\"\"\n",
        desk = crate::desk::SESSION,
        exe = exe.replace(['\'', '"'], "")
    );
    // C-h/j/k/l move between panes: a session and its shell, the desk's
    // columns. The key reaches the program instead when there's no pane
    // that way (so Claude keeps C-j and C-l in a window of its own), on the
    // dashboard, and in vim or fzf. On the desk, a column at the edge gets
    // the key, and its own session moves between the panes it shows.
    let moves: String = [("h", "L", "left"), ("j", "D", "bottom"), ("k", "U", "top"), ("l", "R", "right")]
        .iter()
        .map(|(key, dir, edge)| {
            format!(
                "bind -n C-{key} if -F \"#{{||:#{{pane_at_{edge}}},#{{==:#{{window_name}},dashboard}}}}\" {{ send-keys C-{key} }} {{ if-shell \"{VIM}\" {{ send-keys C-{key} }} {{ select-pane -{dir} }} }}\n"
            )
        })
        .collect();
    format!(
        "{base}bind -n C-g switch-client -t ={session}:=dashboard\n\
         {moves}\
         {side}\
         bind -T grove-finca C-q switch-client -t ={session}\n\
         bind -T grove-shell C-q switch-client -t ={session}\n\
         # C-v in a finca window sends this Mac's clipboard file or image there (transfer.rs).\n\
         bind -T grove-finca C-v {paste}\n\
         bind -T grove-shell C-v {paste}\n\
         bind r source-file \"{}\" \\; display \"Reloaded Grove tmux config\"\n\
         {copy}\
         {theme}\
         \n# Your own setup, loaded last.\n\
         source-file -q \"{}\"\n\
         {ACCOUNT_TAG}",
        self_path.display(),
        local_path.display(),
        theme = tmux_theme(theme),
    )
}

/// The bar, borders, messages and copy-mode highlight in the theme's colours.
/// Every option is set even for Grove's own theme (tmux's stock colours), so
/// re-sourcing after a theme change leaves nothing of the old one behind.
/// tmux.local.conf loads after this, so your own colours still win.
pub fn tmux_theme(t: &Theme) -> String {
    let c = |c: Color| match c {
        Color::Rgb(r, g, b) => format!("#{r:02x}{g:02x}{b:02x}"),
        _ => "default".into(),
    };
    let (status, left, current, border, active, message, mode, alert) = if t.bg == Color::Reset {
        (
            "bg=green,fg=black".to_string(),
            "#[bold] GROVE ".to_string(),
            "#[reverse] #I #W #[default]".to_string(),
            "default".to_string(),
            "fg=green".to_string(),
            "bg=yellow,fg=black".to_string(),
            "bg=yellow,fg=black".to_string(),
            "red".to_string(),
        )
    } else {
        let (bg, fg) = (c(t.bg), c(t.fg));
        (
            format!("bg={bg},fg={fg}"),
            format!("#[bg={},fg={bg},bold] GROVE #[default] ", c(t.accent)),
            format!("#[bg={},fg={bg},bold] #I #W #[default]", c(t.shell)),
            format!("fg={}", c(t.selected_bg)),
            format!("fg={}", c(t.shell)),
            format!("bg={},fg={fg}", c(t.selected_bg)),
            format!("bg={},fg={fg}", c(t.cursor_bg)),
            c(t.needs_you),
        )
    };
    format!(
        "\n# Theme: {name} (theme in config.toml, T on the dashboard).\n\
         set -g status-style \"{status}\"\n\
         set -g status-left \"{left}\"\n\
         setw -g window-status-current-format \"{current}\"\n\
         setw -g window-status-format \"#{{?#{{m:💧 *,#W}},#[fg={alert}#,bold] #I #W #[default],}}\"\n\
         set -g pane-border-style \"{border}\"\n\
         set -g pane-active-border-style \"{active}\"\n\
         set -g message-style \"{message}\"\n\
         setw -g mode-style \"{mode}\"\n",
        name = t.name,
    )
}

/// Whether the pane runs vim or fzf, which take C-h/j/k/l themselves (as
/// vim-tmux-navigator checks).
const VIM: &str = r"ps -o state= -o comm= -t '#{pane_tty}' | grep -iqE '^[^TXZ ]+ +(\\S+\\/)?g?(view|l?n?vim?x?|fzf)(diff)?$'";

/// The window's Claude account (window options set at launch, launch.rs) in
/// front of status-right, whatever status-right your own setup chose. `-F`
/// copies the current value in once; the match keeps reloads from repeating it.
const ACCOUNT_TAG: &str = r##"
# The current window's Claude account, in front of status-right.
set -g @grove_account_tag "#{?@grove_account,#[fg=#{@grove_account_color}#,bold]#{@grove_account}#[default] ,}"
if -F "#{m:*grove_account_tag*,#{status-right}}" "" "set -gF status-right '##{E:@grove_account_tag}#{status-right}'"
"##;

pub fn clipboard_cmd(os: &str, over_ssh: bool, has: &dyn Fn(&str) -> bool) -> Option<String> {
    if over_ssh {
        return None;
    }
    match os {
        "macos" => Some("pbcopy".into()),
        _ if has("wl-copy") => Some("wl-copy".into()),
        _ if has("xsel") => Some("xsel --clipboard --input".into()),
        _ if has("xclip") => Some("xclip -selection clipboard".into()),
        _ => None,
    }
}

/// Whether `prog` is on PATH.
pub fn on_path(prog: &str) -> bool {
    std::env::var_os("PATH")
        .is_some_and(|p| std::env::split_paths(&p).any(|d| d.join(prog).is_file()))
}

/// This grove's path, as written into hooks, MCP config and tmux bindings.
/// Symlinks are resolved, except that a Homebrew install gives the stable
/// `<prefix>/opt/grove/...` link: the versioned Cellar folder is deleted by
/// `brew upgrade`, which would leave every written path dangling.
pub fn grove_exe() -> Result<PathBuf> {
    let exe = std::env::current_exe().context("locating the grove binary")?;
    let exe = exe.canonicalize().unwrap_or(exe);
    Ok(brew_opt_path(&exe).filter(|p| p.exists()).unwrap_or(exe))
}

/// `<prefix>/Cellar/grove/<version>/<rest>` → `<prefix>/opt/grove/<rest>`.
fn brew_opt_path(exe: &Path) -> Option<PathBuf> {
    let parts: Vec<_> = exe.components().collect();
    let i = parts
        .windows(2)
        .position(|w| w[0].as_os_str() == "Cellar" && w[1].as_os_str() == "grove")?;
    let rest = parts.get(i + 3..).filter(|r| !r.is_empty())?;
    let mut p: PathBuf = parts[..i].iter().collect();
    p.push("opt");
    p.push("grove");
    p.extend(rest);
    Some(p)
}

pub fn write_all(
    paths: &Paths,
    grove_bin: &Path,
    session: &str,
    statusline: bool,
    theme: &str,
) -> Result<()> {
    let pretty = |v: serde_json::Value| serde_json::to_string_pretty(&v).map(String::into_bytes);
    write_atomic(
        &paths.run.join("hooks.json"),
        &pretty(hooks_json(grove_bin, statusline))?,
    )?;
    write_atomic(&paths.run.join("mcp.json"), &pretty(mcp_json(grove_bin))?)?;
    write_atomic(
        &paths.run.join("tmux.conf"),
        tmux_conf(
            session,
            paths,
            clipboard_cmd(
                std::env::consts::OS,
                std::env::var_os("SSH_CONNECTION").is_some(),
                &on_path,
            )
            .as_deref(),
            crate::ui::theme::named(theme).unwrap_or(&crate::ui::theme::GROVE),
        )
        .as_bytes(),
    )
}

