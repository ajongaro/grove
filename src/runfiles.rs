//! Files Grove regenerates on every start under `run/`: the hooks settings
//! file, the MCP config, and Grove's tmux config.

use std::path::Path;

use anyhow::Result;
use serde_json::json;

use crate::config::Paths;
use crate::store::write_atomic;

/// Every hook event Grove listens to (see state.rs).
pub const HOOK_EVENTS: [&str; 9] = [
    "SessionStart",
    "UserPromptSubmit",
    "PostToolUse",
    "PostToolUseFailure",
    "PermissionRequest",
    "Notification",
    "Stop",
    "StopFailure",
    "SessionEnd",
];

/// Settings file passed to every session with `--settings`. Exec form
/// (`command` + `args`) so a binary path with spaces needs no quoting.
pub fn hooks_json(grove_bin: &Path) -> serde_json::Value {
    let handler = json!([{ "hooks": [{
        "type": "command",
        "command": grove_bin.to_string_lossy(),
        "args": ["hook"],
        "timeout": 10,
    }]}]);
    let hooks: serde_json::Map<String, serde_json::Value> = HOOK_EVENTS
        .iter()
        .map(|e| (e.to_string(), handler.clone()))
        .collect();
    json!({ "hooks": hooks })
}

pub fn mcp_json(grove_bin: &Path) -> serde_json::Value {
    json!({ "mcpServers": { "grove": { "command": grove_bin.to_string_lossy(), "args": ["mcp"] } } })
}

/// Loaded only by Grove's own tmux server (`tmux -L grove -f run/tmux.conf`).
pub fn tmux_conf(session: &str) -> String {
    let base = r##"# Generated by grove on every start. Edit Grove, not this file.
set -g mouse on
set -g history-limit 50000
set -g base-index 0
set -g renumber-windows off
set -g allow-rename off
set -g set-clipboard on
bind-key -T copy-mode MouseDragEnd1Pane send-keys -X copy-pipe-and-cancel "pbcopy"
bind-key -T copy-mode-vi MouseDragEnd1Pane send-keys -X copy-pipe-and-cancel "pbcopy"

bind-key -n C-y select-window -t :0    # dashboard
bind-key -n C-h previous-window
bind-key -n C-l next-window

set -g status-style "bg=#1f4d2b,fg=#e8f5e9"
set -g status-left "#[bold] GROVE "
set -g status-left-length 12
set -g status-right "#[fg=#a5d6a7]%H:%M "
set -g window-status-current-style "bg=#2e7d32,fg=#ffffff,bold"
"##;
    // Finca sessions use this table instead of root (see finca.rs), so only
    // C-q is intercepted and every other key reaches the remote grove.
    format!("{base}\nbind-key -T grove-finca C-q switch-client -t ={session}\n")
}

pub fn write_all(paths: &Paths, grove_bin: &Path, session: &str) -> Result<()> {
    let pretty = |v: serde_json::Value| serde_json::to_string_pretty(&v).map(String::into_bytes);
    write_atomic(
        &paths.run.join("hooks.json"),
        &pretty(hooks_json(grove_bin))?,
    )?;
    write_atomic(&paths.run.join("mcp.json"), &pretty(mcp_json(grove_bin))?)?;
    write_atomic(&paths.run.join("tmux.conf"), tmux_conf(session).as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hooks_json_registers_every_event_in_exec_form() {
        let bin = Path::new("/Apps/My Tools/grove");
        let v = hooks_json(bin);
        let hooks = v["hooks"].as_object().unwrap();
        assert_eq!(hooks.len(), HOOK_EVENTS.len());
        for ev in HOOK_EVENTS {
            let h = &hooks[ev][0]["hooks"][0];
            assert_eq!(h["type"], "command", "{ev}");
            assert_eq!(h["command"], "/Apps/My Tools/grove", "{ev}");
            assert_eq!(h["args"], serde_json::json!(["hook"]), "{ev}");
        }
    }

    #[test]
    fn mcp_json_points_at_grove_mcp() {
        let v = mcp_json(Path::new("/b/grove"));
        assert_eq!(v["mcpServers"]["grove"]["command"], "/b/grove");
        assert_eq!(v["mcpServers"]["grove"]["args"], serde_json::json!(["mcp"]));
    }

    #[test]
    fn tmux_conf_has_grove_keys() {
        let c = tmux_conf("grove");
        for needle in [
            "bind-key -n C-y select-window -t :0",
            "bind-key -n C-h previous-window",
            "bind-key -n C-l next-window",
            "GROVE",
        ] {
            assert!(c.contains(needle), "missing {needle}");
        }
    }

    #[test]
    fn tmux_conf_binds_c_q_back_to_the_configured_session() {
        assert!(tmux_conf("grove").contains("bind-key -T grove-finca C-q switch-client -t =grove"));
        assert!(tmux_conf("g2").contains("switch-client -t =g2"));
    }

    #[test]
    fn write_all_writes_valid_files_under_spaced_home() {
        let dir = tempfile::tempdir().unwrap();
        let paths = Paths::new(dir.path().join("my grove"));
        write_all(&paths, Path::new("/b/grove"), "grove").unwrap();
        for f in ["hooks.json", "mcp.json"] {
            let text = std::fs::read_to_string(paths.run.join(f)).unwrap();
            serde_json::from_str::<serde_json::Value>(&text).unwrap();
        }
        assert!(paths.run.join("tmux.conf").is_file());
    }
}
